/** Expands the compact seed shape into normalised Product rows. */
export function buildProducts(
  applicationName: (id: string) => string,
  categoryName: (id: string) => string,
): Product[] {
  return SEEDS.map((seed, index) => {
    const id = `prd-${String(index + 1).padStart(3, '0')}`;

    // Deterministic dates spread across the 24 months ending at
    // SEED_REFERENCE_MONTH, so the rolling-12-month trend chart on the
    // dashboard has real shape rather than a flat zero line.
    const monthsAgo = 23 - (index % 24);
    const created = new Date(
      Date.UTC(REFERENCE_YEAR, REFERENCE_MONTH - monthsAgo, ((index * 11) % 27) + 1, 10, 15),
    );
    const updated = new Date(created.getTime() + ((index % 7) + 1) * 86_400_000 * 14);

    return {
      id,
      name: seed.name,
      slug: slugify(seed.name),
      casNumber: seed.cas,
      molecularFormula: seed.formula,
      molecularWeight: seed.mw,
      applicationId: seed.applicationId,
      applicationName: applicationName(seed.applicationId),
      categoryId: seed.categoryId,
      categoryName: categoryName(seed.categoryId),
      status: seed.status,
      description: seed.description,
      synonyms: seed.synonyms,
      createdAt: created.toISOString(),
      updatedAt: updated.toISOString(),
      deletedAt: null,
    } satisfies Product;
  });
}

